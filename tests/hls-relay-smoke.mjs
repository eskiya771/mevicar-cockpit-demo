import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {once} from 'node:events';
const require=createRequire(import.meta.url);
process.env.XTREAM_UPSTREAM='http://127.0.0.1:8080';
process.env.XTREAM_USER='test-user';
process.env.XTREAM_PASSWORD='test-pass';
process.env.MEVITV_BRIDGE_TOKEN='test-token-which-is-at-least-32-characters-long';
process.env.MEVITV_ORIGIN='https://example.github.io';
const realFetch=globalThis.fetch;
let upstreamCalls=[];
const master='#EXTM3U\n#EXT-X-STREAM-INF:BANDWIDTH=2000000\nvariants/720p.m3u8\n';
const variant='#EXTM3U\n#EXT-X-TARGETDURATION:6\n#EXT-X-KEY:METHOD=AES-128,URI="../keys/key.bin"\n#EXTINF:6,\n../segment-1.ts\n';
globalThis.fetch=async (value)=>{
 const u=new URL(value);upstreamCalls.push(u);
 assert.equal(u.origin,'http://127.0.0.1:8080');
 if(u.pathname.endsWith('/42.m3u8'))return new Response(master,{headers:{'content-type':'application/vnd.apple.mpegurl'}});
 if(u.pathname.endsWith('/variants/720p.m3u8'))return new Response(variant,{headers:{'content-type':'application/vnd.apple.mpegurl'}});
 if(u.pathname.endsWith('/keys/key.bin'))return new Response('fake-test-key');
 if(u.pathname.endsWith('/segment-1.ts'))return new Response('fake-ts-segment',{headers:{'content-type':'video/mp2t'}});
 throw Error('unexpected upstream path');
};
const {server}=require('../bridge/server.cjs');
server.listen(0,'127.0.0.1');await once(server,'listening');
const base='http://127.0.0.1:'+server.address().port;
const auth={'Authorization':'Bearer '+process.env.MEVITV_BRIDGE_TOKEN,'Content-Type':'application/json'};
try{
 const response=await realFetch(base+'/ticket',{method:'POST',headers:auth,body:JSON.stringify({type:'live',id:'42',ext:'m3u8'})});
 assert.equal(response.status,200);
 const ticket=(await response.json()).url;
 const first=await realFetch(base+ticket,{headers:{Origin:'https://example.github.io'}});
 assert.equal(first.status,200);
 assert.match(first.headers.get('content-type'),/mpegurl/);
 assert.equal(first.headers.get('access-control-allow-origin'),'https://example.github.io');
 const masterText=await first.text();
 assert(masterText.startsWith('#EXTM3U'));
 assert(!masterText.includes('test-pass'));
 const playlist=masterText.split('\n').find(s=>s.startsWith('/hls/'));
 assert(playlist);
 const nested=await realFetch(base+playlist);
 assert.equal(nested.status,200);
 const nestedText=await nested.text();
 assert(!nestedText.includes('test-user'));
 const keyPath=nestedText.match(/URI="(\/hls\/[^"]+)"/)?.[1];
 const segmentPath=nestedText.split('\n').find(s=>s.startsWith('/hls/'));
 assert(keyPath&&segmentPath);
 assert.equal(await (await realFetch(base+keyPath)).text(),'fake-test-key');
 const segment=await realFetch(base+segmentPath);
 assert.equal(segment.status,200);
 assert.equal(await segment.text(),'fake-ts-segment');
 assert.equal((await realFetch(base+'/hls/invalid')).status,400);
 const {createRelay}=require('../bridge/hls.cjs');
 const relay=createRelay('synthetic-secret','http://127.0.0.1:8080');
 assert.throws(()=>relay.rewrite('#EXTM3U\nhttps://other.example/segment.ts','http://127.0.0.1:8080/test.m3u8','http://localhost'),/outside/);
 assert.throws(()=>relay.open('invalid'),/Invalid/);
 console.log('HLS relay OK: nested variants, segment streaming, key URI rewriting, CORS, signed links, strict upstream host.');
}finally{await new Promise(resolve=>server.close(resolve));globalThis.fetch=realFetch;}
