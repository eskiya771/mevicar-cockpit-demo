/* Real stocks module: no placeholder prices, safe symbols and PWA integration. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const js=readFileSync(new URL('../stocks.js',import.meta.url),'utf8');
const css=readFileSync(new URL('../stocks.css',import.meta.url),'utf8');
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const workflow=readFileSync(new URL('../.github/workflows/pages.yml',import.meta.url),'utf8');
const sw=readFileSync(new URL('../sw.js',import.meta.url),'utf8');
new Function(js);
const store={};
const window={};
const document={getElementById:()=>null,querySelector:()=>null};
runInNewContext(js,{window,document,localStorage:{getItem:key=>store[key]||null,setItem:(key,value)=>store[key]=value},Intl,URLSearchParams,Number,String,JSON,Date,console});
const api=window.MeviStocks;
assert.equal(api.debug().mounted,false);
assert.ok(api.debug().items.includes('TSLA'));
assert.equal(api.validSymbol('SIE:XETR'),true);
for(const bad of ['<script>','AAPL&apikey=bad','', '12345678901234567890123456'])assert.equal(api.validSymbol(bad),false);
const quote=api.parseQuote({close:'102.25',change:'-1.50',percent_change:'-1.45',currency:'EUR',datetime:'2026-11-12'},'SIE:XETR');
assert.equal(quote.close,102.25);
assert.equal(quote.change,-1.5);
assert.equal(quote.currency,'EUR');
assert.throws(()=>api.parseQuote({status:'error',code:429,message:'Too many requests'},'AAPL'));
assert.throws(()=>api.parseQuote({close:'0'},'BAD'));
assert.match(api.html(false),/Aktienkurse/);
assert.match(api.html(true),/is-compact/);
assert.doesNotMatch(api.html(false),/228,40|312,65|198,20|Simulierte Kurse/);
assert.match(js,/https:\/\/api\.twelvedata\.com\/quote/);
assert.doesNotMatch(js,/localStorage\.setItem\([^\n]*key:/);
for(const token of ['window.MeviStocks?.html','window.MeviStocks.mount()','window.MeviStocks.unmount()','stocks-host','./stocks.js','./stocks.css'])assert.ok(html.includes(token),'Index integration: '+token);
assert.ok(css.includes('.mevi-stocks.is-compact'));
assert.ok(workflow.includes('tests/stocks-smoke.mjs'));
assert.ok(workflow.includes('mevicar-stocks-script'));
assert.ok(workflow.includes('stocks.js stocks.css'));
assert.ok(sw.includes("'./stocks.js'")&&sw.includes("'./stocks.css'"));
console.log('Stocks: real quote parsing, safe watchlist symbols, UI lifecycle and PWA bundling passed.');
