import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const api=createRequire(import.meta.url)('../xtream.js');
assert.equal(api.origin('https://iptv.example:8443/path'), 'https://iptv.example:8443');
assert.equal(api.origin('http://iptv.example:8080'),null);
assert.equal(api.origin('https://alice:secret@iptv.example'),null);
const c=api.credentials('https://iptv.example:8443','sample-user','sample-pass');
const url=new URL(api.apiURL(c,'get_live_streams'));
assert.equal(url.pathname,'/player_api.php');
assert.equal(url.searchParams.get('action'),'get_live_streams');
assert.equal(url.searchParams.get('username'),'sample-user');
assert.equal(api.mediaURL(c,'movie',42,'mkv'),'https://iptv.example:8443/movie/sample-user/sample-pass/42.mkv');
assert.throws(()=>api.mediaURL(c,'movie','../x','mp4'));
assert.deepEqual(api.normalizeCategories([{category_id:2,category_name:'Movies'}]),[{id:'2',name:'Movies'}]);
assert.deepEqual(api.normalizeItems([{stream_id:13,name:'News',category_id:2}],'live')[0].id,'13');
assert.deepEqual(api.normalizeItems([{series_id:7,name:'Show'}],'series')[0].id,'7');
api.state.accounts.push({id:'test',categories:{live:[]},items:{live:[{id:'1',name:'News HD',category:'2'},{id:'2',name:'Sports',category:'3'}]}});
api.state.active='test';
assert.equal(api.view('live','2','news').length,1);
api.remove('test');
assert.equal(api.active(),null);
console.log('Xtream OK: HTTPS credential validation, API URLs, catalog normalization, filters and account removal.');
