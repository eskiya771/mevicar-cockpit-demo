import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const stored=new Map([['mevicar-tv-engine-v1','exoplayer']]);
const localStorage={getItem:k=>stored.get(k)||null,setItem:(k,v)=>stored.set(k,String(v))};
const calls=[];
const bridge={postMessage(raw){
 const req=JSON.parse(raw);calls.push(req);
 let result={id:req.id,ok:true};
 if(req.action==='capabilities')result.capabilities={iptvExoplayer:true};
 else if(req.action==='iptv.status')result.configured=true;
 else if(req.action==='iptv.api')result.body=JSON.stringify(req.apiAction.endsWith('categories')?[]:[{stream_id:7,series_id:7,name:'Test'}]);
 else if(req.action!=='iptv.play')throw Error('Unexpected action '+req.action);
 queueMicrotask(()=>bridge.onmessage({data:JSON.stringify(result)}));
}};
const win={MeviNativeBridge:bridge};
const context={window:win,localStorage,URL,console,setTimeout,clearTimeout,setInterval,clearInterval,DOMException,AbortController,fetch(){throw Error('No browser/proxy request permitted in direct mode');}};
runInNewContext(readFileSync('xtream.js','utf8'),context);
const api=win.meviXtream;
assert(await api.nativeReady());
assert(api.nativeSelected());
const account=await api.connect('Direct',{nativeDirect:true});
assert.equal(account.items.live[0].id,'7');
assert.equal(calls.filter(x=>x.action==='iptv.api').length,6);
assert(calls.every(x=>!JSON.stringify(x).includes('synology')));
await assert.rejects(api.playbackURL(account.credentials,'live','7','ts'),/ExoPlayer/);
const controller=new AbortController();controller.abort();
await assert.rejects(api.epg(account,'7',{signal:controller.signal}),{name:'AbortError'});
await api.nativeRequest('iptv.play',{type:'live',mediaId:'7',extension:'ts'});
assert.equal(calls.at(-1).mediaId,'7');
assert(!Object.hasOwn(calls.at(-1),'url'),'Provider stream URLs remain native');
const browser={};
runInNewContext(readFileSync('xtream.js','utf8'),{...context,window:browser});
assert.equal(browser.meviXtream.nativeSelected(),false,'Web browser never selects Android player');
assert.equal(await browser.meviXtream.nativeReady(),false);
console.log('Native IPTV: direct catalog transport, no proxy/browser fetch, secret-free playback command, abort and Web fallback passed');
