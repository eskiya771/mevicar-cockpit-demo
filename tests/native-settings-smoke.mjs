import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const navigation=read('native-navigation/MeviNavigationActivity.java');
const secure=read('native-navigation/MeviSecureSettingsPlugin.java');
const installer=read('scripts/install-native-navigation.py');
const settings=read('credential-settings.js');
assert.match(navigation,/MeviSecureSettingsPlugin\.readStored\(this,"mapsKey"\)/);
assert.doesNotMatch(navigation,/EditText\s+input|putString\("api_key"/);
assert.match(secure,/AndroidKeyStore/);
assert.match(secure,/AES\/GCM\/NoPadding/);
assert.match(secure,/@CapacitorPlugin\(name="MeviSecureSettings"\)/);
assert.match(secure,/@PluginMethod public void set/);
assert.match(secure,/@PluginMethod public void remove/);
assert.match(secure,/@PluginMethod public void status/);
assert.doesNotMatch(secure,/reply\.put\("value"/);
assert.match(installer,/registerPlugin\(MeviSecureSettingsPlugin\.class\)/);
assert.match(settings,/global\.Capacitor\?\.Plugins\?\.MeviSecureSettings/);
console.log('Native Settings: Keystore, Settings-only SDK key, plugin registration, no secret readback OK');
